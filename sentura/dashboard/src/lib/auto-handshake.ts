/**
 * Auto-handshake — when Forge successfully deploys a new employee, the
 * dashboard creates a fresh `agent:<newId>:dashboard:<uuid>` session for the
 * new employee and seeds it with an "introduce yourself" prompt. The new
 * employee's own LLM (running with its newly-written workspace files) then
 * generates the handshake reply, so the operator sees a welcome conversation
 * authored by the actual employee — not by Forge.
 *
 * The trigger lives in /create/page.tsx (onToolCall hook) so this works for
 * any deploy initiated from the dashboard. Other deploy paths (CLI, scripted)
 * skip the handshake silently.
 */

import type { GatewayClient } from "./gateway/client";

export interface OperatorProfile {
  name?: string | null;
  email?: string | null;
}

export interface TriggerAutoHandshakeOptions {
  client: GatewayClient;
  newAgentId: string;
  newAgentName?: string | null;
  operator: OperatorProfile;
  enabled?: boolean;
}

export interface AutoHandshakeResult {
  sessionKey: string;
  handshakePrompt: string;
}

/**
 * Compose the system prompt sent to the freshly-deployed employee. The new
 * employee will read this as the operator's first message and reply in its
 * own voice using its native workspace files (SOUL.md, IDENTITY.md, AGENTS.md
 * Hard Rules, TOOLS.md, BOOTSTRAP.md Enterprise Context).
 *
 * T0/T1 only — never include tier-classified data, secrets, or PII beyond the
 * operator's display name.
 */
export function composeHandshakePrompt(params: {
  newAgentName?: string | null;
  operatorName?: string | null;
}): string {
  const operator = params.operatorName?.trim() || "Operator";
  const me = params.newAgentName?.trim() || "your new AI employee";

  return [
    `Hi ${operator} — I just finished my own onboarding.`,
    "",
    `Please introduce yourself as ${me}. In one short message, cover:`,
    "",
    "1. **Who I am**: name, role, one-line mission.",
    "2. **What I can do today**: three concrete sample tasks I am ready to handle.",
    "3. **Where I escalate**: my Hard Rules / approval thresholds — anything I will hand off to a human and to whom.",
    "4. **What I am wired into**: tools, MCP servers, channels (only what is configured today, no aspirational claims).",
    "5. **How to reach me**: dashboard route or channel binding.",
    "",
    "Read my own SOUL.md, IDENTITY.md, AGENTS.md (especially the Hard Rules section), TOOLS.md, and BOOTSTRAP.md Enterprise Context to ground every claim.",
    "",
    "Keep it under 200 words. T0/T1 information only — do not echo any secrets, tokens, or tier-classified data.",
  ].join("\n");
}

/**
 * Compose a friendly label for the new conversation as it appears in the
 * /chat sidebar. Falls back to the agent id when no name is available.
 */
export function composeHandshakeLabel(
  newAgentName?: string | null,
  newAgentId?: string | null,
): string {
  const display = newAgentName?.trim() || newAgentId?.trim() || "new employee";
  return `Welcome from ${display}`;
}

/**
 * Create a dashboard session keyed to the newly-deployed employee and seed
 * it with the handshake prompt. Returns the session key on success, or null
 * if the feature is disabled / the RPC failed.
 *
 * The new employee's first reply is generated by its own runtime — this
 * helper does NOT impersonate the employee. It only opens the session and
 * delivers the prompt; OpenClaw routes the response back through the normal
 * `chat` event stream.
 */
export async function triggerAutoHandshake(
  options: TriggerAutoHandshakeOptions,
): Promise<AutoHandshakeResult | null> {
  const { client, newAgentId, newAgentName, operator, enabled = true } = options;

  if (!enabled) return null;
  if (!newAgentId || typeof newAgentId !== "string") return null;

  const handshakePrompt = composeHandshakePrompt({
    newAgentName,
    operatorName: operator.name ?? operator.email ?? null,
  });

  const label = composeHandshakeLabel(newAgentName, newAgentId);

  try {
    const result = await client.createChatSession(newAgentId, {
      initialMessage: handshakePrompt,
      label,
    });
    if (!result?.key) return null;
    return { sessionKey: result.key, handshakePrompt };
  } catch (err) {
    console.warn("[auto-handshake] sessions.create failed:", err);
    return null;
  }
}
