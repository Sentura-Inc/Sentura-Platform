/**
 * Pure scoring + persistence helpers for sentura-experience-extraction.
 *
 * Split from index.ts so test scripts can import them without pulling in the
 * `openclaw/plugin-sdk/plugin-entry` runtime alias (which is only resolvable
 * inside the gateway process via jiti).
 *
 * Confidence formula (matches sentura/skills/experience-extraction/SKILL.md):
 *   confidence = min(0.9, 0.3 + 0.1 * sqrt(occurrences))
 */

import fs from "node:fs";
import path from "node:path";

export interface CandidateEntry {
  signature: string;
  occurrences: number;
  firstSeen: string; // ISO-8601 UTC
  lastSeen: string;  // ISO-8601 UTC
  sampleSessionKeys: string[];
  confidence: number;
  /** Set to the linkId once promoted; absent until then. */
  promotedAs?: string;
}

export interface CandidateFile {
  agentId: string;
  candidates: CandidateEntry[];
  updatedAt: string;
}

export const MAX_SAMPLE_KEYS = 5;
export const MAX_TOOL_SEQUENCE = 12;

export function computeSignature(toolSequence: string[]): string {
  const trimmed = toolSequence.slice(0, MAX_TOOL_SEQUENCE);
  return trimmed.join(">");
}

export function computeConfidence(occurrences: number): number {
  if (occurrences <= 0) return 0;
  return Math.min(0.9, 0.3 + 0.1 * Math.sqrt(occurrences));
}

export function shouldPromote(
  candidate: CandidateEntry,
  cfg: { minOccurrences: number; confidenceThreshold: number },
): boolean {
  if (candidate.promotedAs) return false;
  if (candidate.occurrences < cfg.minOccurrences) return false;
  if (candidate.confidence < cfg.confidenceThreshold) return false;
  return true;
}

export function updateCandidate(
  existing: CandidateEntry | undefined,
  signature: string,
  sessionKey: string,
  now: string,
): CandidateEntry {
  if (!existing) {
    return {
      signature,
      occurrences: 1,
      firstSeen: now,
      lastSeen: now,
      sampleSessionKeys: [sessionKey],
      confidence: computeConfidence(1),
    };
  }
  const occurrences = existing.occurrences + 1;
  const sampleSessionKeys = existing.sampleSessionKeys.includes(sessionKey)
    ? existing.sampleSessionKeys
    : [...existing.sampleSessionKeys, sessionKey].slice(-MAX_SAMPLE_KEYS);
  return {
    ...existing,
    occurrences,
    lastSeen: now,
    sampleSessionKeys,
    confidence: computeConfidence(occurrences),
  };
}

function candidateFilePath(candidatesDir: string, agentId: string): string {
  return path.join(candidatesDir, agentId, "candidates.json");
}

export function loadCandidateFile(candidatesDir: string, agentId: string): CandidateFile {
  const filePath = candidateFilePath(candidatesDir, agentId);
  if (!fs.existsSync(filePath)) {
    return { agentId, candidates: [], updatedAt: new Date(0).toISOString() };
  }
  try {
    const raw = fs.readFileSync(filePath, "utf-8");
    return JSON.parse(raw) as CandidateFile;
  } catch {
    return { agentId, candidates: [], updatedAt: new Date(0).toISOString() };
  }
}

export function saveCandidateFile(candidatesDir: string, file: CandidateFile): void {
  const filePath = candidateFilePath(candidatesDir, file.agentId);
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, JSON.stringify(file, null, 2));
}

export function writeExperienceLink(
  workspaceRoot: string,
  agentId: string,
  candidate: CandidateEntry,
  finalSnippet: string,
): string {
  const linkDir = path.join(workspaceRoot, agentId, "ekg", "workflows", "experience-links");
  fs.mkdirSync(linkDir, { recursive: true });
  const stamp = new Date().toISOString();
  const linkId = `expl-${candidate.signature.replace(/[^a-z0-9]/gi, "-").slice(0, 40)}-${Date.now()}`;
  const linkPath = path.join(linkDir, `${linkId}.json5`);
  const body = {
    id: linkId,
    type: "experience-link",
    pattern: {
      tools: candidate.signature.split(">").filter(Boolean),
      finalSnippet,
    },
    occurrences: candidate.occurrences,
    confidence: candidate.confidence,
    firstSeen: candidate.firstSeen,
    lastSeen: candidate.lastSeen,
    provenance: {
      source: "sentura-experience-extraction",
      extractedAt: stamp,
    },
  };
  fs.writeFileSync(linkPath, `// Auto-generated by sentura-experience-extraction\n${JSON.stringify(body, null, 2)}\n`);
  return linkId;
}

const META_AGENTS = new Set([
  "creator",
  "tuner",
  "orchestrator",
  "mcp-builder",
  "data-scavenger",
  "main",
]);

export function isMetaAgent(agentId: string): boolean {
  return META_AGENTS.has(agentId);
}
